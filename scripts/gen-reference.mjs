#!/usr/bin/env node
// REFERENCE GENERATOR (single source of truth). Reads the code that already DECLARES the channels,
// tools, hooks, and schema, and writes docs/reference/*.md from it. Never hand-list those facts in
// prose: that is what drifts. Run after any change to the declarations; run in CI with --check to
// FAIL the build if the committed docs are stale.
//
//   node scripts/gen-reference.mjs           # write docs/reference/*.md
//   node scripts/gen-reference.mjs --check    # exit 1 if any committed doc differs from a fresh run
//
// Sources of truth (the only places these facts live):
//   src/spine/db.ts                 -> the 7-channel `Channel` union + the table DDL
//   src/coverage/standard-tools.json -> the 29 tools (+ provenance)
//   src/coverage/standard-hooks.json -> the 30 hooks (+ provenance)
//   src/coverage/groups.ts           -> each hook's mechanism + assigned channel(s); each tool's group
//
// Dependency-free (node stdlib only) and deterministic (no timestamps), so --check is stable.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(ROOT, p), "utf8");
const BANNER = (sources) =>
  `<!-- GENERATED by scripts/gen-reference.mjs from ${sources}. Do not edit by hand. -->\n` +
  `<!-- Re-run \`node scripts/gen-reference.mjs\`; CI runs \`--check\` and fails if this is stale. -->\n\n`;

// ---- parse the sources -----------------------------------------------------------------------
const dbTs = read("src/spine/db.ts");
const groupsTs = read("src/coverage/groups.ts");
const toolsDoc = JSON.parse(read("src/coverage/standard-tools.json"));
const hooksDoc = JSON.parse(read("src/coverage/standard-hooks.json"));

// 7 channels: the `Channel` union line in db.ts
const chanLine = dbTs.match(/export type Channel\s*=\s*([^;]+);/);
if (!chanLine) throw new Error("could not find the Channel union in db.ts");
const CHANNELS = [...chanLine[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);

// table DDL: each CREATE TABLE IF NOT EXISTS <name> ( ... );
const TABLES = [...dbTs.matchAll(/CREATE TABLE IF NOT EXISTS (\w+) \(([\s\S]*?)\);/g)].map((m) => ({
  name: m[1],
  ddl: `CREATE TABLE ${m[1]} (${m[2].replace(/\s+$/, "")}\n);`,
}));

// per-hook mechanism + assigned channel(s) from HOOK_SPECS
const hookSpecsBlock = groupsTs.match(/HOOK_SPECS:\s*HookSpec\[\]\s*=\s*\[([\s\S]*?)\n\];/)[1];
const HOOK_SPECS = [...hookSpecsBlock.matchAll(/\{\s*name:\s*"([^"]+)",\s*mechanism:\s*"([^"]+)",\s*channels:\s*\[([^\]]*)\][^}]*\}/g)].map((m) => ({
  name: m[1],
  mechanism: m[2],
  channels: [...m[3].matchAll(/"([^"]+)"/g)].map((x) => x[1]),
}));

// per-tool group from TOOL_SPECS
const toolSpecsBlock = groupsTs.match(/TOOL_SPECS:\s*ToolSpec\[\]\s*=\s*\[([\s\S]*?)\n\];/)[1];
const TOOL_SPECS = [...toolSpecsBlock.matchAll(/\{\s*name:\s*"([^"]+)",\s*group:\s*"([^"]+)"\s*\}/g)].map((m) => ({
  name: m[1],
  group: m[2],
}));

// ---- integrity cross-checks (the generator also validates the code's internal consistency) ----
const problems = [];
if (CHANNELS.length !== 7) problems.push(`expected 7 channels, found ${CHANNELS.length}`);
if (toolsDoc.tools.length !== 29) problems.push(`standard-tools.json count ${toolsDoc.tools.length} != 29`);
if (hooksDoc.hooks.length !== 30) problems.push(`standard-hooks.json count ${hooksDoc.hooks.length} != 30`);
if (TOOL_SPECS.length !== toolsDoc.tools.length) problems.push(`TOOL_SPECS ${TOOL_SPECS.length} != tools ${toolsDoc.tools.length}`);
if (HOOK_SPECS.length !== hooksDoc.hooks.length) problems.push(`HOOK_SPECS ${HOOK_SPECS.length} != hooks ${hooksDoc.hooks.length}`);
for (const h of HOOK_SPECS) for (const c of h.channels) if (!CHANNELS.includes(c)) problems.push(`hook ${h.name} -> unknown channel ${c}`);
const toolGroup = Object.fromEntries(TOOL_SPECS.map((t) => [t.name, t.group]));
for (const t of toolsDoc.tools) if (!(t.name in toolGroup)) problems.push(`tool ${t.name} missing from TOOL_SPECS`);
if (problems.length) {
  console.error("INTEGRITY FAILURE (the code's own declarations disagree):\n  " + problems.join("\n  "));
  process.exit(2);
}

// ---- render the four reference docs --------------------------------------------------------
function channelsMd() {
  // For each channel, the hooks assigned to it (from HOOK_SPECS). Tools land on the join channels.
  const TOOL_JOIN = new Set(["message_stream", "gate", "otel"]); // verify.ts: the 3-channel tool join
  const lines = [];
  lines.push(BANNER("src/spine/db.ts (the `Channel` union) + src/coverage/groups.ts"));
  lines.push(`# Channels (${CHANNELS.length})\n`);
  lines.push("The `Channel` union (`src/spine/db.ts`). Every captured event lands on exactly one.\n");
  lines.push("| channel | hooks assigned here | carries the tool join |");
  lines.push("|---|---|---|");
  for (const c of CHANNELS) {
    const hks = HOOK_SPECS.filter((h) => h.channels.includes(c)).map((h) => h.name);
    lines.push(`| \`${c}\` | ${hks.length ? hks.map((h) => `\`${h}\``).join(", ") : "-"} | ${TOOL_JOIN.has(c) ? "yes" : "-"} |`);
  }
  lines.push("\n> A tool is `fired_verified` only with all three join channels on one `tool_use_id`");
  lines.push("> (`message_stream` tool_use + `gate` PreToolUse.gate + `otel` tool_result), plus a `gate`");
  lines.push("> `neo.decision` for the human-seat group. A hook fires on its assigned channel(s) above.\n");
  return lines.join("\n");
}

function toolsMd() {
  const lines = [];
  lines.push(BANNER("src/coverage/standard-tools.json + src/coverage/groups.ts (TOOL_SPECS)"));
  lines.push(`# Tools (${toolsDoc.tools.length})\n`);
  lines.push(`> Provenance: ${toolsDoc.provenance}\n`);
  for (const grp of ["query", "agent", "human"]) {
    const names = TOOL_SPECS.filter((t) => t.group === grp).map((t) => t.name);
    lines.push(`## group: \`${grp}\` (${names.length})\n`);
    lines.push("| tool | kind |");
    lines.push("|---|---|");
    for (const n of names) {
      const kind = toolsDoc.tools.find((t) => t.name === n)?.kind ?? "?";
      lines.push(`| \`${n}\` | ${kind} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

function hooksMd() {
  const lines = [];
  lines.push(BANNER("src/coverage/standard-hooks.json + src/coverage/groups.ts (HOOK_SPECS)"));
  lines.push(`# Hooks (${hooksDoc.hooks.length})\n`);
  lines.push(`> Provenance: ${hooksDoc.hooks.length} HookEvent members. ${hooksDoc.provenance}\n`);
  lines.push("Each hook, the trigger mechanism that fires it, and the channel(s) a real row must land on.\n");
  lines.push("| hook | mechanism | assigned channel(s) |");
  lines.push("|---|---|---|");
  for (const h of HOOK_SPECS) {
    lines.push(`| \`${h.name}\` | ${h.mechanism} | ${h.channels.map((c) => `\`${c}\``).join(", ")} |`);
  }
  lines.push("\n> This is the declared denominator (what the code targets). How many actually fire on a");
  lines.push("> given workload is organic and is reported per run, not fixed here.\n");
  return lines.join("\n");
}

function schemaMd() {
  const lines = [];
  lines.push(BANNER("src/spine/db.ts (the table DDL + the `Channel` union)"));
  lines.push("# Spine schema\n");
  lines.push("The canonical SQLite record. Tables (verbatim DDL from `src/spine/db.ts`):\n");
  for (const t of TABLES) {
    lines.push(`## \`${t.name}\`\n`);
    lines.push("```sql\n" + t.ddl + "\n```\n");
  }
  lines.push("## `events.channel` enum\n");
  lines.push(CHANNELS.map((c) => `\`${c}\``).join(" | ") + "\n");
  return lines.join("\n");
}

const FILES = {
  "docs/reference/channels.md": channelsMd(),
  "docs/reference/tools.md": toolsMd(),
  "docs/reference/hooks.md": hooksMd(),
  "docs/reference/schema.md": schemaMd(),
};

// ---- write or check --------------------------------------------------------------------------
const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, content] of Object.entries(FILES)) {
  const abs = join(ROOT, rel);
  if (check) {
    const cur = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (cur !== content) { stale++; console.error(`STALE: ${rel} (re-run scripts/gen-reference.mjs)`); }
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    console.log(`wrote ${rel}`);
  }
}
if (check) {
  if (stale) { console.error(`\n${stale} reference doc(s) STALE.`); process.exit(1); }
  console.log("reference docs up to date.");
} else {
  console.log(`\nOK: ${CHANNELS.length} channels, ${toolsDoc.tools.length} tools, ${hooksDoc.hooks.length} hooks, ${TABLES.length} tables.`);
}
